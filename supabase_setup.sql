-- 1. ADICIONAR COLUNAS FALTANTES NA TABELA PRODUCTS (SE NECESSÁRIO)
ALTER TABLE IF EXISTS public.products 
  ADD COLUMN IF NOT EXISTS description text,
  ADD COLUMN IF NOT EXISTS category text,
  ADD COLUMN IF NOT EXISTS image_url text,
  ADD COLUMN IF NOT EXISTS fotos text[] DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS em_destaque boolean DEFAULT true,
  ADD COLUMN IF NOT EXISTS is_active boolean DEFAULT true;

-- Criar tabela products se não existir
CREATE TABLE IF NOT EXISTS public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz DEFAULT now(),
  title text NOT NULL,
  description text,
  price numeric(10,2) NOT NULL DEFAULT 0,
  category text,
  image_url text,
  fotos text[] DEFAULT '{}',
  em_destaque boolean DEFAULT true,
  is_active boolean DEFAULT true
);

-- 2. TABELA DE BANNERS
ALTER TABLE IF EXISTS public.banners 
  ADD COLUMN IF NOT EXISTS description text;

CREATE TABLE IF NOT EXISTS public.banners (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz DEFAULT now(),
  title text,
  subtitle text,
  description text,
  image_url text NOT NULL,
  button_text text,
  button_link text,
  display_order integer DEFAULT 1,
  is_active boolean DEFAULT true
);

-- 3. TABELA DE CÍRCULOS DE DESTAQUE (CATEGORIAS NA HOME)
CREATE TABLE IF NOT EXISTS public.circulos_destaque (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz DEFAULT now(),
  nome text NOT NULL,
  img_url text NOT NULL,
  link text,
  ordem integer DEFAULT 0
);

-- Inserir círculos padrão caso a tabela esteja vazia
