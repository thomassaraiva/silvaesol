-- 8. CONFIGURAÇÃO DO BUCKET DE STORAGE PARA FOTOS (midias)
INSERT INTO storage.buckets (id, name, public)
VALUES ('midias', 'midias', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Políticas de Storage para o bucket 'midias'
DROP POLICY IF EXISTS "Leitura publica de midias" ON storage.objects;
CREATE POLICY "Leitura publica de midias"
ON storage.objects FOR SELECT
USING (bucket_id = 'midias');

DROP POLICY IF EXISTS "Upload publico de midias" ON storage.objects;
CREATE POLICY "Upload publico de midias"
ON storage.objects FOR INSERT
WITH CHECK (bucket_id = 'midias');

DROP POLICY IF EXISTS "Atualizacao publica de midias" ON storage.objects;
CREATE POLICY "Atualizacao publica de midias"
ON storage.objects FOR UPDATE
USING (bucket_id = 'midias');

DROP POLICY IF EXISTS "Exclusao publica de midias" ON storage.objects;
CREATE POLICY "Exclusao publica de midias"
ON storage.objects FOR DELETE
USING (bucket_id = 'midias');
