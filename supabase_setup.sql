WHERE NOT EXISTS (SELECT 1 FROM public.circulos_destaque LIMIT 1);

-- 4. ATIVAR ROW LEVEL SECURITY (RLS)
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.banners ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.circulos_destaque ENABLE ROW LEVEL SECURITY;

-- 5. POLÍTICAS DE ACESSO PARA TABELA PRODUCTS
